# 用 DP：dp[i][k] = 前 i 镜切成 k 段是否可行
$dp=@{}
for($k=1;$k -le 9;$k++){ $dp["0,$k"]=$true }
for($i=1;$i -le $n;$i++){
  for($k=1;$k -le 9;$k++){
    $ok=$false
    for($j=0;$j -lt $i;$j++){
      if($dp.ContainsKey("$j,$($k-1)") -and $dp["$j,$($k-1)"]){
        if((Sum $j $i) -le 15){ $ok=$true; break }
      }
    }
    $dp["$i,$k"]=$ok
  }
}
