# 先枚举所有能把 35 镜切成 8~9 段且每段<=15s 的方案，取段数最少者
$n=$shots.Count
$prefix=New-Object 'int[]' ($n+1)
for($i=0;$i -lt $n;$i++){ $prefix[$i+1]=$prefix[$i]+$shots[$i][2] }
function Sum($a,$b){ return $prefix[$b]-$prefix[$a] }  # 镜 a..b-1 (0-indexed,半开)

