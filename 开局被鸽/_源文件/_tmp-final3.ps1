$ErrorActionPreference='Stop'
# ASCII-only validator: seg | shotid | label | dur
$rows = @(
 @(1,'1-1','L187a',3), @(1,'1-2','L187b',2), @(1,'1-3','none',4),
 @(2,'2-1','L190a',2), @(2,'2-2','L190b',2), @(2,'2-3','none',2), @(2,'2-4','L195',2), @(2,'2-5','L198a',3),
 @(3,'3-1','L198b',3), @(3,'3-2','L201a',2), @(3,'3-3','L201b',3), @(3,'3-4','L201c',2), @(3,'3-5','L205a',4),
 @(4,'4-1','L205b',3), @(4,'4-2','L208',3), @(4,'4-3','L212a',4), @(4,'4-4','L212b',4),
 @(5,'5-1','L215',4), @(5,'5-2','L218',3), @(5,'5-3','L221',2), @(5,'5-4','L224',4),
 @(6,'6-1','L227a',4), @(6,'6-2','L227b',3), @(6,'6-3','L230a',4), @(6,'6-4','L230b',4),
 @(7,'7-1','L230c',4), @(7,'7-2','L233a',4), @(7,'7-3','L233b',3), @(7,'7-4','L236',4),
 @(8,'8-1','L239a',4), @(8,'8-2','L239b',3), @(8,'8-3','none',3), @(8,'8-4','none',3)
)
$tot=0
foreach($seg in 1..8){
  $rs = $rows | Where-Object { $_[0] -eq $seg }
  $s=($rs | ForEach-Object { $_[3] } | Measure-Object -Sum).Sum
  $n=$rs.Count
  $flag = if($s -gt 15){'  ** OVER 15s **'}else{''}
  $lbl = ($rs | ForEach-Object { "$($_[1])=$($_[3])" }) -join ' '
  Write-Host ("seg{0} : {1}s | {2} shots | {3}{4}" -f $seg,$s,$n,$lbl,$flag)
  $tot+=$s
}
Write-Host ("TOTAL = {0}s | {1} shots | segments = 8" -f $tot,$rows.Count)
