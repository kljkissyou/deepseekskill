$ErrorActionPreference='Stop'
# seg | shot | label | dur | needSeconds
$plan = @(
 @(1,'1-1','187a',3,3), @(1,'1-2','187b',2,2), @(1,'1-3','none',4,0),
 @(2,'2-1','190a',2,2), @(2,'2-2','190b',2,2), @(2,'2-3','none',2,0), @(2,'2-4','195',2,2), @(2,'2-5','198a',3,3),
 @(3,'3-1','198b',3,3), @(3,'3-2','201a',2,2), @(3,'3-3','201b',3,3), @(3,'3-4','201c',2,4), @(3,'3-5','none',2,0), @(3,'3-6','205a',4,4),
 @(4,'4-1','205b',3,3), @(4,'4-2','208',3,3), @(4,'4-3','212a',4,4), @(4,'4-4','212b',4,4),
 @(5,'5-1','215',4,4), @(5,'5-2','218',3,3), @(5,'5-3','221',2,2), @(5,'5-4','224',4,4),
 @(6,'6-1','227a',4,4), @(6,'6-2','227b',3,3), @(6,'6-3','230a',4,4), @(6,'6-4','230b',4,4),
 @(7,'7-1','230c',4,4), @(7,'7-2','233a',4,4), @(7,'7-3','233b',3,3), @(7,'7-4','236',4,4),
 @(8,'8-1','239a',4,4), @(8,'8-2','239b',3,3), @(8,'8-3','none',3,0), @(8,'8-4','none',3,0)
)
$bad=0
Write-Host "--- per-shot checks ---"
foreach($r in $plan){
  if($r[3] -gt 4){ Write-Host ("OVER4: {0} dur={1}" -f $r[1],$r[3]); $bad++ }
  if($r[4] -gt 0 -and $r[3] -lt $r[4]){ Write-Host ("TOOSHORT: {0} dur={1} need={2}" -f $r[1],$r[3],$r[4]); $bad++ }
}
Write-Host "--- per-segment ---"
$tot=0
foreach($seg in 1..8){
  $rs=$plan|Where-Object{$_[0] -eq $seg}
  $s=($rs|ForEach-Object{$_[3]}|Measure-Object -Sum).Sum
  $flag=if($s -gt 15){' ** OVER15 **'; $bad++}else{''}
  Write-Host ("seg{0}: {1}s {2}shots{3}" -f $seg,$s,$rs.Count,$flag)
  $tot+=$s
}
Write-Host ("TOTAL {0}s / {1} shots / 8 segments / problems={2}" -f $tot,$plan.Count,$bad)
